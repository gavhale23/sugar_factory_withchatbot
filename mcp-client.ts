import process from "node:process";
import readline from "node:readline/promises";
import "dotenv/config";
import OpenAI from "openai";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";

// 1. Configuration & Environment Variables
const apiKey = process.env.OPENAI_API_KEY;
if (!apiKey || apiKey === "your_openai_api_key_here") {
  console.error(
    "Error: Please open the .env file in F:\\mcp and replace 'your_openai_api_key_here' with your actual OpenAI API key."
  );
  process.exit(1);
}

const databaseUrl = process.env.DATABASE_URL;
if (!databaseUrl) {
  console.error("Error: Missing DATABASE_URL environment variable.");
  process.exit(1);
}

// Configurable model name (default: gpt-4.1-mini)
const MODEL = process.env.OPENAI_MODEL || "gpt-4.1-mini";

// Default question for Sanjivani Sugar Factory assistant
const DEFAULT_QUESTION =
  "Which farmers supplied more than 100 tonnes of sugarcane and have pending payments? Show their names, villages, supply quantities, and payment status.";

async function main() {
  // 2. Initialize official OpenAI client
  const openai = new OpenAI({
    apiKey: apiKey,
  });

  // 3. Initialize official MCP client
  const mcpClient = new Client(
    {
      name: "sanjivani-ai-farmer-client",
      version: "1.0.0",
    },
    {
      capabilities: {},
    }
  );

  // 4. Configure Stdio transport to spawn mcp-server.ts using Node and local tsx CLI
  const transport = new StdioClientTransport({
    command: process.execPath,
    args: ["./node_modules/tsx/dist/cli.mjs", "mcp-server.ts"],
    env: {
      ...process.env,
      DATABASE_URL: databaseUrl,
    } as Record<string, string>,
  });

  // Setup terminal interactive input
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
  });

  try {
    // 5. Connect MCP client to MCP server
    console.log("Connecting to MCP Server via stdio transport...");
    await mcpClient.connect(transport);
    console.log("Connected successfully to MCP Server.\n");

    // 6. Discover available tools dynamically from MCP server
    const toolsResult = await mcpClient.listTools();
    console.log(
      `Discovered tool(s): ${toolsResult.tools.map((t) => t.name).join(", ")}\n`
    );

    // 7. Convert MCP tools into OpenAI Responses API function-tool format
    const openAiTools = toolsResult.tools.map((tool) => ({
      type: "function" as const,
      name: tool.name,
      description: tool.description || "",
      parameters: {
        type: "object",
        properties: (tool.inputSchema as any)?.properties ?? {},
        required: (tool.inputSchema as any)?.required ?? [],
        additionalProperties: false,
      },
      strict: true,
    }));

    console.log("==================================================");
    console.log("🌾 Sanjivani Sugar Factory AI Farmer Assistant 🌾");
    console.log("==================================================");
    console.log("Ask any question about farmers, sugarcane supply, or payments.");
    console.log("Type 'exit' to quit, or press Enter directly for the default query.");

    // Interactive question loop
    while (true) {
      const userInput = await rl.question("\n👉 Enter your question (or 'exit'): ");
      const trimmed = userInput.trim();

      if (trimmed.toLowerCase() === "exit" || trimmed.toLowerCase() === "quit") {
        console.log("Exiting assistant. Goodbye!");
        break;
      }

      const question = trimmed.length > 0 ? trimmed : DEFAULT_QUESTION;
      if (trimmed.length === 0) {
        console.log(`[Using default question]: "${question}"`);
      }

      console.log(`\nThinking & querying OpenAI (Model: ${MODEL})...`);

      // 8. Prepare initial input message for OpenAI Responses API
      const inputItems: any[] = [{ role: "user", content: question }];

      // First request: Ask OpenAI Responses API with the discovered tools
      const initialResponse = await openai.responses.create({
        model: MODEL,
        input: inputItems,
        tools: openAiTools,
      });

      // 9. Inspect response output to detect any function calls requested by the model
      const toolCall = initialResponse.output.find(
        (item) => item.type === "function_call"
      );

      if (toolCall && toolCall.type === "function_call") {
        console.log(`[MCP Tool Request] OpenAI called: "${toolCall.name}"`);

        // Parse arguments generated by OpenAI (if any)
        const callArgs = toolCall.arguments ? JSON.parse(toolCall.arguments) : {};

        // 10. Execute the requested tool through the MCP client
        const toolExecutionResult = await mcpClient.callTool({
          name: toolCall.name,
          arguments: callArgs,
        });

        // Extract tool output text from MCP result
        const toolOutputText = (toolExecutionResult.content as any[])
          .map((c) => (c.type === "text" ? c.text : JSON.stringify(c)))
          .join("\n");

        console.log("[MCP Tool Result] Data received from PostgreSQL. Generating response...\n");

        // 11. Prepare continuation input containing:
        // - The original user question
        // - The model's initial output items (including the function_call item)
        // - The function_call_output item with matching call_id
        const continuationInput = [
          ...inputItems,
          ...initialResponse.output,
          {
            type: "function_call_output" as const,
            call_id: toolCall.call_id,
            output: toolOutputText,
          },
        ];

        // Second request: Send tool results back to OpenAI to get final answer
        const finalResponse = await openai.responses.create({
          model: MODEL,
          input: continuationInput as any,
          tools: openAiTools,
        });

        console.log("=== AI Assistant Answer ===");
        console.log(finalResponse.output_text);
      } else {
        // Model responded directly without calling a tool
        console.log("=== AI Assistant Answer ===");
        console.log(initialResponse.output_text);
      }
    }
  } catch (error: any) {
    console.error("\nAn error occurred during execution:", error?.message || error);
  } finally {
    // 12. Clean up readline, MCP client, and child processes
    rl.close();
    console.log("\nClosing MCP client connection...");
    try {
      await mcpClient.close();
      await transport.close();
    } catch {
      // Ignore errors during transport teardown
    }
    console.log("Shutdown complete.");
  }
}

main().catch((err) => {
  console.error("Unhandled error:", err);
  process.exit(1);
});
